"""Write THIRD_PARTY_LICENSES.md: every crate compiled into the Linux
binary, its licence, and the licence/notice files it ships.

Run: make notices   (dev only; needs cargo and the crates in ~/.cargo).
"""
import json, os, subprocess, sys

def main(out):
    tree = subprocess.run(
        ["cargo", "tree", "-e", "normal", "--target", "x86_64-unknown-linux-musl", "--prefix", "none", "--format", "{p}"],
        capture_output=True, text=True, check=True).stdout
    shipped = set()
    for line in tree.splitlines():
        parts = line.replace(" (*)", "").split()
        if len(parts) >= 2 and parts[0] != "plica":
            shipped.add((parts[0], parts[1].lstrip("v")))
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1"], capture_output=True, text=True, check=True).stdout)
    pkgs = {(p["name"], p["version"]): p for p in meta["packages"]}
    lines = [
        "# Third-party licences",
        "",
        "Plica is built from the following Rust crates. Each is listed with its",
        "licence and the licence and notice files it ships. Generated by",
        "`make notices`; do not edit by hand.",
        "",
    ]
    seen = {}  # licence text -> where it was first given in full
    for name, ver in sorted(shipped):
        p = pkgs.get((name, ver))
        if p is None:
            print(f"warning: no metadata for {name} {ver}", file=sys.stderr)
            continue
        lines.append(f"## {name} {ver}")
        lines.append("")
        lines.append(f"Licence: {p.get('license') or p.get('license_file') or 'unknown'}")
        if p.get("repository"):
            lines.append(f"Source: {p['repository']}")
        lines.append("")
        root = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(root) if f.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")))
        for f in files:
            path = os.path.join(root, f)
            if not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8", errors="replace") as fh:
                text = fh.read().strip()
            if text in seen:
                lines.append(f"{f}: the same text as {seen[text]}.")
                lines.append("")
                continue
            seen[text] = f"{f} of {name} {ver}"
            lines.append(f"<details><summary>{f}</summary>")
            lines.append("")
            lines.append("```text")
            lines.append(text.replace("```", "'''"))
            lines.append("```")
            lines.append("")
            lines.append("</details>")
            lines.append("")
        if not files:
            lines.append("(No licence file in the crate; see its licence above.)")
            lines.append("")
    # The syntax grammars inside two-face carry their own licences.
    grammars = subprocess.run(["cargo", "run", "-q", "--release", "--example", "grammar_licences"],
                              capture_output=True, text=True, check=True).stdout
    entries = [e.split("\n", 1) for e in grammars.split("@@@ ")[1:]]
    lines += [
        "# Syntax grammars",
        "",
        "The syntax colouring grammars come with two-face (the set `bat` ships).",
        "Those whose licences ask for acknowledgement:",
        "",
    ]
    for path, text in entries:
        text = text.strip()
        lines.append(f"## {path.strip()}")
        lines.append("")
        if text in seen:
            lines.append(f"The same text as {seen[text]}.")
            lines.append("")
            continue
        seen[text] = f"the licence of {path.strip()}"
        lines += ["<details><summary>Licence</summary>", "", "```text", text.replace("```", "'''"), "```", "", "</details>", ""]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{out}: {len(shipped)} crates, {len(entries)} grammar licences")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "THIRD_PARTY_LICENSES.md")
